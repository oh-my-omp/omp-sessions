//! Prints the TypeScript declarations of the wire protocol (src/protocol.rs
//! and the error kinds). The package commits the output as
//! `src/engine/protocol.ts`; `bun run check` fails when they differ.

use engine::error::{EngineError, ErrorKind};
use engine::protocol::{Context, DirEntry, Op, PROTOCOL, Reply, Request, Response, UrlParts};
use ts_rs::{Config, TS};

fn main() {
	// u64 fields are JSON numbers on the wire, never bigint.
	let cfg = Config::new().with_large_int("number");
	let decls = [
		ErrorKind::decl(&cfg),
		EngineError::decl(&cfg),
		Context::decl(&cfg),
		UrlParts::decl(&cfg),
		Op::decl(&cfg),
		Request::decl(&cfg),
		DirEntry::decl(&cfg),
		Reply::decl(&cfg),
		Response::decl(&cfg),
	];
	let mut out = String::from("// Generated by `cargo run --features ts --bin protocol-ts` from engine/src/protocol.rs. Do not edit.\n\n");
	out.push_str(&format!("export const PROTOCOL = {PROTOCOL};\n"));
	for decl in decls {
		out.push_str("\nexport ");
		out.push_str(&decl);
		out.push('\n');
	}
	print!("{out}");
}
